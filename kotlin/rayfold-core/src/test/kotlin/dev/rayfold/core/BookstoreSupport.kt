/** A raw HTTP/1.1 exchange, for headers the JDK client will not send (Host) and for requests it would rewrite. */
class RawResponse(val status: Int, val head: String, val body: String) {
    fun header(name: String): String? = head.split("\r\n").drop(1).firstOrNull { it.substringBefore(':').trim().equals(name, ignoreCase = true) }?.substringAfter(':')?.trim()
}

/** Sends [request] as is (it should say `Connection: close`) and reads until the server closes; bounded by a 5 s socket timeout. */
fun rawHttp(port: Int, request: String): RawResponse = Socket("127.0.0.1", port).use { s ->
    s.soTimeout = 5000
    s.getOutputStream().write(request.toByteArray())
    s.getOutputStream().flush()
    val text = readAll(s.getInputStream()).toString(Charsets.UTF_8)
    val end = text.indexOf("\r\n\r\n")
    val head = if (end < 0) text else text.substring(0, end)
    RawResponse(head.substringAfter(' ').substringBefore(' ').toIntOrNull() ?: 0, head, if (end < 0) "" else text.substring(end + 4))
}

fun readAll(input: InputStream): ByteArray {
    val out = ByteArrayOutputStream()
    val buf = ByteArray(8192)
    while (true) {
        val n = try { input.read(buf) } catch (e: java.net.SocketException) { -1 }
        if (n < 0) return out.toByteArray()
        out.write(buf, 0, n)
    }
}
