import { afterAll, describe, expect, it } from "vitest";
import { bounded } from "../../../e2e/wait.ts";
import { generateKotlin, generateTypeScript, loadSchema } from "./index.ts";

const SHOP = `
"""A book on the shelf."""
entity Book { id: ID """shown on the spine""" title: String pages: Int? tags: [String] price: Money format: Format }
scalar Money
enum Format { PAPER EBOOK }
object Card { title: String }
union Found = Book | Card
input Draft { title: String copies: Int = 1 note: String? }
event BookAdded { id: ID }
query book(id: ID): Book?
query books(page: PageArgs = { first: 20 }): Page<Book>
query search(q: String): [Found]
command addBook(draft: Draft): Book throws Duplicate { title: String } emits BookAdded
stream added: BookAdded
`;

const shop = loadSchema(SHOP);

const KOTLIN_EDGES = String.raw`
input Prefs { notify: Boolean in: Int? }
enum Format { PAPER in EBOOK }
input Filter {
  format: Format = PAPER
  formats: [Format] = [PAPER, in]
  score: Float = 0.5
  min: Float = 1
  big: Float = 1e21
  price: String = "$5 and ${"$"}{x} \f"
  meta: JSON = { "a-b": [1, true] }
  page: PageArgs = { first: 5 }
  prefs: Prefs = { notify: true }
}
"""Closes */ early, /* nests, and keeps \u0041 as text."""
entity Account { id: ID type: String when: String class: String? }
query a(p: Prefs, f: Filter, in: Int = 3, object: Format = EBOOK): Account
`;

const TS = `/* Generated by \`rayfold gen ts\`. Do not edit. */

export interface Page<T> { items: T[]; cursor: string | null; hasMore: boolean; total?: number | null }
export interface PageArgs { first?: number; after?: string | null; offset?: number | null }

/** A book on the shelf. */
export interface Book {
  $type: "Book";
  id: string;
  /** shown on the spine */
  title: string;
  pages?: number | null;
  tags: Array<string>;
  price: string;
  format: Format;
}

export type Money = string | number;

export type Format = "PAPER" | "EBOOK";

export interface Card {
  title: string;
}

export type Found = Book | Card;

export interface Draft {
  title: string;
  copies?: number;
  note?: string | null;
}

export interface BookAdded {
  id: string;
}

export interface Duplicate {
  title: string;
}

export interface Ops {
  book: { kind: "query"; args: { id: string }; result: Book | null; error: never };
  books: { kind: "query"; args: { page?: PageArgs }; result: Page<Book>; error: never };
  search: { kind: "query"; args: { q: string }; result: Array<Found>; error: never };
  addBook: { kind: "command"; args: { draft: Draft }; result: Book; error: { type: "Duplicate"; data: Duplicate } };
  added: { kind: "stream"; args: Record<string, never>; result: BookAdded; error: never };
}

export type Queries = { [K in keyof Ops as Ops[K]["kind"] extends "query" ? K : never]: Ops[K] };
export type Commands = { [K in keyof Ops as Ops[K]["kind"] extends "command" ? K : never]: Ops[K] };
export type Streams = { [K in keyof Ops as Ops[K]["kind"] extends "stream" ? K : never]: Ops[K] };

export interface Events { BookAdded: BookAdded; }

export const OP_KINDS = {"book":"query","books":"query","search":"query","addBook":"command","added":"stream"} as const;
`;

