const work = mkdtempSync(join(tmpdir(), "rayfold-gen-ts-kotlin-"));
afterAll(() => rmSync(work, { recursive: true, force: true }));

describe("generateTypeScript", () => {
  it("prints every kind of type and each operation's signature", () => {
    expect(shop.warnings).toEqual([]);
    expect(generateTypeScript(shop.ir)).toBe(TS);
  });

  it("drops the header on request", () => {
    expect(generateTypeScript(shop.ir, { header: false })).toBe(TS.slice(TS.indexOf("\n\n") + 2));
  });

  it("compiles under tsc --strict, and the types reject what the schema forbids", async () => {
    writeFileSync(join(work, "shop.ts"), generateTypeScript(shop.ir));
    // uses the generated types the way a caller does; the @ts-expect-error lines fail the compile if a type is too loose
    writeFileSync(
      join(work, "use.ts"),
      [
        `import type { Book, Commands, Draft, Events, Found, Ops, Queries, Streams } from "./shop.ts";`,
        `import { OP_KINDS } from "./shop.ts";`,
        `const book: Book = { $type: "Book", id: "b1", title: "Dune", tags: [], price: "9.99", format: "PAPER" };`,
        `const draft: Draft = { title: "Dune" };`,
        `const found: Found[] = [book, { title: "card" }];`,
        `const q: keyof Queries = "search";`,
        `const c: keyof Commands = "addBook";`,
        `const s: keyof Streams = "added";`,
        `const e: Events["BookAdded"] = { id: "b1" };`,
        `const err: Ops["addBook"]["error"] = { type: "Duplicate", data: { title: "Dune" } };`,
        `const kind: "command" = OP_KINDS.addBook;`,
        `// @ts-expect-error format is an enum`,
        `const badFormat: Book["format"] = "HARDBACK";`,
        `// @ts-expect-error addBook is not a query`,
        `const notQuery: keyof Queries = "addBook";`,
        `// @ts-expect-error title is required`,
        `const noTitle: Draft = { copies: 2 };`,
        `export { book, draft, found, q, c, s, e, err, kind, badFormat, notQuery, noTitle };`,
      ].join("\n") + "\n",
    );
    const tsc = join(dirname(createRequire(import.meta.url).resolve("typescript/package.json")), "bin", "tsc");
    const args = [tsc, "--noEmit", "--strict", "--target", "es2022", "--module", "nodenext", "--allowImportingTsExtensions", join(work, "use.ts")];
    const result = await bounded(
      new Promise<{ code: number; out: string }>((resolve) =>
        execFile(process.execPath, args, { cwd: work, timeout: 30_000 }, (e, stdout, stderr) => resolve({ code: e ? ((e as { code?: number }).code ?? -1) : 0, out: stdout + stderr })),
      ),
      "tsc finishes",
      30_000,
    );
    expect(result).toEqual({ code: 0, out: "" });
  }, 40_000);
});

describe("generateKotlin", () => {
  it("prints serializable data classes, argument classes and op kinds in the package asked for", () => {
    expect(generateKotlin(shop.ir, { pkg: "shop.gen" })).toBe(KOTLIN);
  });

  it("defaults the package", () => {
    expect(generateKotlin(shop.ir)).toBe(KOTLIN.replace("package shop.gen", "package dev.rayfold.generated"));
  });

  // The file this generates is compiled by the Kotlin build (rayfold-core's tests) and used by GeneratedKotlinTest.kt,
  // which is what proves the output compiles: a keyword field, a field named type, enum, Float and JSON defaults, a $
  // in a string and comment text that would close or nest a comment. Regenerate it with UPDATE_GOLDEN=1.
  it("writes Kotlin that compiles for names and defaults Kotlin reads differently (the checked-in file the Kotlin build compiles)", () => {
    const golden = new URL("../../../kotlin/rayfold-core/src/test/kotlin/dev/rayfold/generated/edges/Edges.kt", import.meta.url);
    const text = generateKotlin(loadSchema(KOTLIN_EDGES).ir, { pkg: "dev.rayfold.generated.edges" });
    if (process.env["UPDATE_GOLDEN"]) writeFileSync(golden, text);
    expect(text).toBe(readFileSync(golden, "utf8"));
    expect(text).toContain('    @SerialName("\\$type") val type_: String = "Account",\n    val id: String,\n    val type: String,\n    val `when`: String,');
    expect(text).toContain("    val format: Format = Format.PAPER,\n    val formats: List<Format> = listOf(Format.PAPER, Format.`in`),");
    expect(text).toContain("    val min: Double = 1.0,\n    val big: Double = 1e+21,");
    expect(text).toContain('    val price: String = "\\$5 and \\${x} \\u000c",');
    expect(text).toContain('    val meta: kotlinx.serialization.json.JsonElement = kotlinx.serialization.json.Json.parseToJsonElement("{\\"a-b\\":[1,true]}"),');
    expect(text).toContain("/** Closes * / early, / * nests, and keeps \\u0041 as text. */");
  });

  it("guard - a name that is not a Kotlin keyword and an entity with no type field are written as before", () => {
    const text = generateKotlin(loadSchema(`entity A { id: ID when2: Int } query a: A`).ir);
    expect(text).toContain('    @SerialName("\\$type") val type: String = "A",\n    val id: String,\n    val when2: Int,');
  });

  it("an object with no fields is a plain class, not an empty data class", () => {
    const { ir } = loadSchema(`object Empty {} query e: Empty`);
    expect(generateKotlin(ir).split("\n").slice(12, 15)).toEqual(["@Serializable", "class Empty", ""]);
  });
});
